// Inline **bold** and %%italic%% markup (not _x_: file names are full of underscores).
function runs(text, base = {}) {
  const out = [];
  const re = /(\*\*[^*]+\*\*|%%[^%]+%%)/g;
  let last = 0, m;
  while ((m = re.exec(text))) {
    if (m.index > last) out.push(run(text.slice(last, m.index), base));
    const t = m[0];
    if (t.startsWith("**")) out.push(run(t.slice(2, -2), { ...base, bold: true }));
    else out.push(run(t.slice(2, -2), { ...base, italics: true }));
    last = m.index + t.length;
  }
  if (last < text.length) out.push(run(text.slice(last), base));
  return out;
}

