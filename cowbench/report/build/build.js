function cell(content, width, o = {}) {
  const paras = (Array.isArray(content) ? content : [content]).map((c) =>
    c instanceof Paragraph ? c : new Paragraph({
      children: typeof c === "string" ? runs(c, { size: 19, bold: o.bold }) : c,
      alignment: o.align || AlignmentType.LEFT, spacing: { after: 0, line: 252 },
    }));
  return new TableCell({
    children: paras, width: { size: width, type: WidthType.DXA },
    shading: o.fill ? { type: ShadingType.CLEAR, fill: o.fill, color: "auto" } : undefined,
    margins: { top: 60, bottom: 60, left: 100, right: 100 },
    borders: { top: BORDER, bottom: BORDER, left: BORDER, right: BORDER },
  });
}

// widths: fractions summing to 1; numeric columns (index >= numFrom) right-aligned
function table(headers, rows, fractions, o = {}) {
  const numFrom = o.numFrom ?? 1;
  const widths = fractions.map((f) => Math.round(f * CONTENT));
  widths[widths.length - 1] += CONTENT - widths.reduce((a, b) => a + b, 0);
  const align = (i) => (i >= numFrom ? AlignmentType.RIGHT : AlignmentType.LEFT);
  const head = new TableRow({
    tableHeader: true,
    children: headers.map((h, i) => cell(h, widths[i], { bold: true, fill: HEAD_FILL, align: align(i) })),
  });
  const body = rows.map((r) => new TableRow({
    cantSplit: true,
    children: r.map((c, i) => cell(c, widths[i], { align: align(i), bold: o.boldRows && o.boldRows.includes(rows.indexOf(r)) })),
  }));
  return [
    new Table({
      width: { size: CONTENT, type: WidthType.DXA }, columnWidths: widths,
      layout: TableLayoutType.FIXED, rows: [head, ...body],
    }),
    new Paragraph({ children: [], spacing: { after: 120 } }),
  ];
}

function image(file, widthPx, caption) {
  const buf = fs.readFileSync(path.join(HERE, file));
  // PNG/JPEG pixel size for the aspect ratio
  let w, h;
  if (file.endsWith(".png")) { w = buf.readUInt32BE(16); h = buf.readUInt32BE(20); }
  else { const d = jpegSize(buf); w = d.w; h = d.h; }
  return [
    new Paragraph({
      alignment: AlignmentType.CENTER, spacing: { before: 80, after: 60 }, keepNext: true,
      children: [new ImageRun({
        type: file.endsWith(".png") ? "png" : "jpg", data: buf,
        transformation: { width: widthPx, height: Math.round(widthPx * h / w) },
      })],
    }),
    new Paragraph({ alignment: AlignmentType.CENTER, spacing: { after: 200 }, children: runs(caption, { size: 18, color: INK2, italics: true }) }),
  ];
}
function jpegSize(buf) {
  let i = 2;
  while (i < buf.length) {
    if (buf[i] !== 0xff) { i++; continue; }
    const marker = buf[i + 1], len = buf.readUInt16BE(i + 2);
    if (marker >= 0xc0 && marker <= 0xc3) return { h: buf.readUInt16BE(i + 5), w: buf.readUInt16BE(i + 7) };
    i += 2 + len;
  }
  throw new Error("jpeg size not found");
}

